export type Phrase = {
  id: string;
  zh: string;
  pinyin: string;
  en: string;
  tip?: string;
};

export type BasicsSection = {
  id: string;
  title: string;
  hanzi: string;
  blurb: string;
  phrases: Phrase[];
};

type Row = [zh: string, pinyin: string, en: string, tip?: string];

function section(
  id: string,
  title: string,
  hanzi: string,
  blurb: string,
  rows: Row[],
): BasicsSection {
  return {
    id,
    title,
    hanzi,
    blurb,
    phrases: rows.map(([zh, pinyin, en, tip], index) => ({
      id: `${id}-${index + 1}`,
      zh,
      pinyin,
      en,
      tip,
    })),
  };
}

